import { describe, it, expect } from "vitest";
import { WitBindgen } from "@hpcc-js/wasm-wit-bindgen";
import { expectReadmeVersion } from "../../util/tests/readme-version.ts";

const TEST_WIT = `package example:test;

world test-world {
    export greet: func(name: string) -> string;
}
`;

const COMPLEX_WIT = `package example:complex;

interface logger {
    enum level {
        debug,
        info,
        warn,
        error,
    }

    record entry {
        level: level,
        message: string,
    }

    log: func(entry: entry);
}

world app {
    import logger;
    export run: func() -> result<_, string>;
}
`;

const decode = (bytes: Uint8Array) => new TextDecoder().decode(bytes);

describe("wit-bindgen", function () {
    it("version", async function () {
        const witBindgen = await WitBindgen.load();
        expect(witBindgen).toBeInstanceOf(WitBindgen);
        expect(await WitBindgen.load()).toBe(witBindgen);
        const v = witBindgen.version();
        expect(v).toMatch(/^\d+\.\d+/);
        expectReadmeVersion("wit-bindgen", v);
    });

    it("validate", async function () {
        const witBindgen = await WitBindgen.load();
        expect(witBindgen.validate(TEST_WIT)).toBe(true);
        expect(witBindgen.validate("")).toBe(false);
        expect(witBindgen.validate("this is not wit")).toBe(false);

        expect(witBindgen.validateDetailed(TEST_WIT)).toEqual({ valid: true });
        expect(witBindgen.validateDetailed("  ")).toMatchObject({ valid: false, errorType: "validation" });
        expect(witBindgen.validateDetailed("this is not wit")).toMatchObject({ valid: false, errorType: "parsing" });
    });

    it("validate multiple files", async function () {
        const witBindgen = await WitBindgen.load();
        const main = `package local:demo;

world my-world {
    import host;
    export another-interface;
}

interface host {
    ping: func();
}
`;
        const sourceFiles = {
            "/virtual/a.wit": main,
            "/virtual/b.wit": "interface another-interface {\n    pong: func();\n}\n"
        };
        expect(witBindgen.validate(main, { sourcePath: "/virtual/a.wit", sourceFiles })).toBe(true);
        expect(witBindgen.validate(main)).toBe(false);
    });

    it("introspection", async function () {
        const witBindgen = await WitBindgen.load();
        expect(witBindgen.extractInterfaces(COMPLEX_WIT)).toEqual(["logger"]);
        expect(witBindgen.extractInterfaces("not wit")).toEqual([]);
        expect(witBindgen.hasWorldDefinition(COMPLEX_WIT)).toBe(true);
        expect(witBindgen.hasWorldDefinition("package example:none;")).toBe(false);
        expect(witBindgen.isWitFileExtension("a.WIT")).toBe(true);
        expect(witBindgen.isWitFileExtension("a.wasm")).toBe(false);
    });

    describe("generateBindings", function () {
        const languages = [
            { lang: "rust", extension: ".rs", expectedContent: "fn greet" },
            { lang: "c", extension: ".h", expectedContent: "uint8_t" },
            { lang: "cpp", extension: ".h", expectedContent: "namespace" },
            { lang: "go", extension: ".go", expectedContent: "package" },
            { lang: "csharp", extension: ".cs", expectedContent: "namespace" },
            { lang: "moonbit", extension: ".mbt", expectedContent: "Generated by" },
            { lang: "markdown", extension: ".md", expectedContent: "World test-world" },
        ] as const;

        for (const { lang, extension, expectedContent } of languages) {
            it(lang, async function () {
                const witBindgen = await WitBindgen.load();
                const files = witBindgen.generateBindings(TEST_WIT, lang);
                const mainFile = Object.entries(files).find(([name]) => name.endsWith(extension));
                expect(mainFile, `${lang} should generate a ${extension} file`).toBeDefined();
                const text = decode(mainFile![1]);
                expect(text).toContain(expectedContent);
                expect(text).not.toContain("no longer supported");

                const complex = witBindgen.generateBindings(COMPLEX_WIT, lang);
                expect(Object.keys(complex).some(name => name.endsWith(extension))).toBe(true);
            });
        }

        it("aliases and world selection", async function () {
            const witBindgen = await WitBindgen.load();
            const names = (lang: Parameters<WitBindgen["generateBindings"]>[1]) => Object.keys(witBindgen.generateBindings(TEST_WIT, lang)).sort();
            expect(names("c++")).toEqual(names("cpp"));
            expect(names("md")).toEqual(names("markdown"));
            expect(Object.keys(witBindgen.generateBindings(TEST_WIT, "rust", { worldName: "test-world" })).length).toBeGreaterThan(0);
        });

        it("unsupported language", async function () {
            const witBindgen = await WitBindgen.load();
            const files = witBindgen.generateBindings(TEST_WIT, "cobol" as never);
            expect(Object.keys(files)).toEqual(["error.txt"]);
            expect(decode(files["error.txt"])).toContain("Unsupported language");
        });

        it("languages produce different output", async function () {
            const witBindgen = await WitBindgen.load();
            const outputs = languages.map(({ lang }) => JSON.stringify(Object.keys(witBindgen.generateBindings(TEST_WIT, lang)).sort()));
            expect(new Set(outputs).size).toBe(languages.length);
        });
    });

    it("invalid components", async function () {
        const witBindgen = await WitBindgen.load();
        expect(witBindgen.extractWitFromComponent(new Uint8Array([0, 1, 2, 3]))).toBe("");
        expect(witBindgen.extractCoreWasmFromComponent(new Uint8Array([0, 1, 2, 3]))).toEqual({});
    });
});
